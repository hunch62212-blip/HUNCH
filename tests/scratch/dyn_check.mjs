import RAPIER from '@dimforge/rapier3d-compat';
import { Sim } from '../../src/sim/sim.js';
import { vehicleDynamics, predictPath } from '../../src/sim/dynamics.js';
await RAPIER.init();
const sim = new Sim(RAPIER, { seed: 866201175 });
const R = sim.rover;
const run = (s) => { for (let i = 0; i < s * 120; i++) sim.stepOnce(); };
const show = (l) => { const d = vehicleDynamics(R); console.log(l, JSON.stringify(Object.fromEntries(Object.entries(d).map(([k, v]) => [k, typeof v === 'number' ? +v.toFixed(3) : v])))); };
run(4); show('rest');
R.brake = false; R.cmd.vx = 2; run(10); show('2m/s');
R.cmd.wz = 0.15; run(6); show('turn');
const p = R.pose(); console.log(predictPath(p, 2, 0.15, 8, 4).map((q) => `${q.x.toFixed(1)},${q.z.toFixed(1)}`).join(' | '), 'pose', p.x.toFixed(1), p.z.toFixed(1), (p.yaw * 57.3).toFixed(0));
run(1); const p2 = R.pose(); console.log('1s later', p2.x.toFixed(1), p2.z.toFixed(1));
