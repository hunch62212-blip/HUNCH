import RAPIER from '@dimforge/rapier3d-compat';
import { Sim } from '../../src/sim/sim.js';
await RAPIER.init();
let t=performance.now();
const sim = new Sim(RAPIER);
console.log('build ms', (performance.now()-t).toFixed(0));
const A = sim.autonomy;
const T = {};
const wrapT = (name, obj, fn) => { const f = obj[fn].bind(obj); obj[fn] = (...a) => { const s = performance.now(); const r = f(...a); T[name] = (T[name]||0) + performance.now()-s; return r; }; };
for (const m of sim.modules) wrapT(m.constructor.name, m, 'update');
wrapT('rover.step', sim.rover, 'step');
wrapT('world.step', sim.world, 'step');
wrapT('streamRocks', sim, 'streamRocks');
A.start('cycle', A.missionCycle());
t = performance.now();
const N = 120*Number(process.argv[2]||300);
for (let i=0;i<N;i++) sim.stepOnce();
const wall = performance.now()-t;
console.log('sim s', sim.time.toFixed(0), 'wall s', (wall/1000).toFixed(1), 'x realtime', (sim.time/(wall/1000)).toFixed(1), 'ms/step', (wall/N).toFixed(3));
for (const [k,v] of Object.entries(T).sort((a,b)=>b[1]-a[1])) console.log(k.padEnd(14), (v/N).toFixed(3),'ms/step', (100*v/wall).toFixed(1)+'%');
console.log(A.phase, '|', A.detail);
