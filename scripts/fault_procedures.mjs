// Prints docs/FAULT_PROCEDURES.md from the FDIR catalogue in src/sim/health.js (the code is the source of truth).
//   node scripts/fault_procedures.mjs > docs/FAULT_PROCEDURES.md
import { MODES, LRUS, BAYS, bayOf } from '../src/sim/health.js';
import { ROVER, FAILURES } from '../src/sim/config.js';

const kneel = ROVER.ride.kneel;
const out = [];
const p = (s = '') => out.push(s);
const lam = MODES.reduce((s, m) => s + m.inst.length / m.mtbfH, 0);

p('# AEGIS-V1 failure catalogue and procedures');
p();
p('Generated by `node scripts/fault_procedures.mjs` from `src/sim/health.js`. Do not edit by hand.');
p();
p(`${MODES.length} failure modes on ${Object.keys(LRUS).length} replaceable units. All MTBFs are **[ASSUMED]** engineering estimates.`);
p(`Summed over every unit the rover would see a failure every ~${(1 / lam).toFixed(0)} h of operation; the simulator's`);
p(`random-failure switch multiplies that rate (\`failures on demo\` = ${FAILURES.presets.demo}x, one every ~${(60 / (lam * FAILURES.presets.demo)).toFixed(1)} min of sim time).`);
p();
p('Severity: **caution** = no mission impact, fix at the next stop; **warning** = degraded (derate or redundancy lost);');
p('**critical** = the rover stops or safes itself. Effect: **physics** = the simulator changes the vehicle model;');
p('**annunciation** = only the sensor channel and the alarm are modelled.');
p();
p('## Service bays');
p();
p('Working height is with the rover knelt (ride ' + kneel.toFixed(2) + ' m).');
p();
p('| Bay | Where | Access | Working height |');
p('|---|---|---|---|');
for (const [, b] of Object.entries(BAYS)) p(`| ${b.name} | ${b.where} | ${b.door} | ${(b.workH ?? b.pos[1] + kneel).toFixed(2)} m${b.workH ? ' (service position)' : ''} |`);
p();
p('Design rules for every bay: front access only, no unit behind another unit, captive fasteners, one tool');
p('(7/16 in EVA hex driver), blind-mate connectors on slide rails, units under 25 kg unless dock-serviced, a BIT');
p("lamp on each door, and a door interlock that opens the bay's solid-state breaker (no live 400 V with the door open).");
p();
p('## Replaceable units');
p();
p('| Unit | Name | Bay | Qty | kg | Repair | Time | Prototype part |');
p('|---|---|---|---|---|---|---|---|');
for (const [id, L] of Object.entries(LRUS)) p(`| ${id} | ${L.name} | ${L.bay} | ${L.qty} | ${L.kg} | ${L.where} | ${L.min} min | ${L.proto} |`);
p();
p('## Failure modes');
for (const m of MODES) {
  const L = LRUS[m.lru], b = BAYS[bayOf(m, m.inst[0])];
  p();
  p(`### \`fault ${m.id}${m.inst[0] == null ? '' : ' <' + m.inst.join('|') + '>'}\` - ${m.name}`);
  p();
  p(`* **Severity / effect:** ${m.sev} / ${m.fidelity}. MTBF ${m.mtbfH.toLocaleString('en-US')} h per unit.`);
  p(`* **Cause:** ${m.cause}.`);
  p(`* **Unit and location:** ${m.lru || 'none (transient)'}${L ? ` (${L.name})` : ''}; ${b.name}, ${b.where}.`);
  p(`* **Sensors:** ${m.sensors.join('; ')}.`);
  p(`* **Detection rule:** ${m.detect}.${m.latent ? ' Latent until the unit is used or the periodic BIT runs.' : ''}`);
  p(`* **Automatic response:** ${m.response}.`);
  for (const o of m.operator) p(`* **Operator:** ${o}.`);
  if (L) {
    p(`* **Repair** (${L.where}, ${L.min} min, \`repair ${m.id}${m.inst[0] == null ? '' : ' <unit>'}\`):`);
    const steps = ['Park on < 5 deg slope, set spring brakes, autonomy hold', 'Kneel (ride -0.65 m): the bays drop to working height', 'Open the bay door: interlock opens its solid-state breaker; check 0 V at the bay test point', ...L.steps, 'Close the door (interlock re-arms the breaker)', 'Run the unit built-in test (BIT) and a 10 s functional check; confirm the alarm clears'];
    steps.forEach((s, i) => p(`  ${i + 1}. ${s}`));
  }
}
console.log(out.join('\n'));
