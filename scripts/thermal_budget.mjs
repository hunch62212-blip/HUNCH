// Closed-form night-energy and hot-day budget, old (12 m^2 vault radiator, 420 kWh-pack battery numbers) against the rescaled model.
// Writes docs/THERMAL_BUDGET.md. Pure arithmetic (src/sim/thermalBudget.js), no sim stepping.   node scripts/thermal_budget.mjs [--print]
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { THERMAL, ROVER, POWER_DOCK, RADIATOR } from '../src/sim/config.js';
import { survivalNight, dockCarriesNight, hotDayVault, hotDayBattery } from '../src/sim/thermalBudget.js';
import { RAD_ALPHA } from '../src/sim/lunarParams.js';

const f = (v, d = 1) => Number(v).toFixed(d);
const OLD = { vault: { ...THERMAL.vault, radArea: 12 }, battery: { ...THERMAL.battery, radArea: 3, C: 2.4e6 }, leakWperK: { vault: 0.25, battery: 0.4 } };
const NEW = {};
const sN = survivalNight(NEW), sO = survivalNight(OLD);
const trim = { vault: { ...THERMAL.vault, survivalSetC: -30 }, battery: { ...THERMAL.battery, survivalSetC: -20 } };
const sT = survivalNight(trim);
const rhu = survivalNight({ ...trim, hotelW: 40, rhu: { vault: 40, battery: 60 } });
const row = (n, s) => `| ${n} | ${f(s.vaultHeater, 0)} | ${f(s.battHeater, 0)} | ${f(s.hubs, 0)} | ${f(s.loadW, 0)} | ${f(s.nightKWh, 0)} kWh | **${f(s.packPct, 0)} %** |`;
const dk = (s) => dockCarriesNight(s.loadW);
const hot = (cfg, a) => hotDayVault({ cfg, alpha: a });
const out = `# Thermal and energy budget (closed form)

Generated by \`node scripts/thermal_budget.mjs\` from \`src/sim/thermalBudget.js\` (the equations of \`health.js\` _thermal at equilibrium). Do not edit by hand.
Review item 7: at 150 kWh a 354 h night did not fit the 25 % limit and the thermal model still used the old geometry.

## What was wrong in the model

* **Vault radiator.** \`THERMAL.vault.radArea\` was 12 m². The radiator hung on the body is \`RADIATOR\` = 2 × ${RADIATOR.len} × ${RADIATOR.h} m = **${f(THERMAL.vault.radArea, 2)} m²** (the 12 m² was the legacy 8000 kg body at K_LEGACY). It is now derived from \`RADIATOR\`.
* **Battery.** \`C\` 2.4e6 J/K and 3 m² were tuned for the 420 kWh pack (2400 kg at 175 Wh/kg). The 150 kWh pack is ${Math.round(150000 / 175)} kg: C = ${f(THERMAL.battery.C / 1e6, 2)}e6 J/K, radiator ${f(THERMAL.battery.radArea, 2)} m² (area ∝ mass^2/3), box leak ${THERMAL.leakWperK.battery} W/K (was 0.4).
* **The "154 W survival load" was a transient.** \`tests/fdir.mjs\` E ran 60 s + 600 s after forcing the vault to its set point, so the heaters were still catching up (vault time constant C / 200 W/K = 600 s, battery 12,000 s). The equilibrium load with the old 12 m² radiator was about ${f(sO.loadW, 0)} W (${f(sO.packPct, 0)} % of the pack per night), not 154 W (36 %).

## Night survival, steady state (354 h, no sun, regolith sink 100 K)

Load = 60 W hotel (flight computer, beacon, BMS) + 3 W arm standby + vault heater (set point ${THERMAL.vault.survivalSetC} °C, closed louvers) + battery heater (${THERMAL.battery.survivalSetC} °C) + six hubs held at ${THERMAL.hubFreezeC} °C.

| Case | Vault heater W | Battery heater W | Hubs W | Rover load W | 354 h | Pack |
|---|---|---|---|---|---|---|
${row('Old geometry (12 m² vault, 3 m² battery, 0.4 W/K)', sO)}
${row('Rescaled (this change)', sN)}
${row('Rescaled + survival set points vault −30 °C, battery −20 °C', sT)}
${row('... + 40 W hotel and 100 W of isotope heat (RHU), not adopted', rhu)}

Set points −30 °C / −20 °C are within typical non-operating ratings (electronics −40 °C, LFP storage −20 °C) [ASSUMED]; they are listed, not applied: this needs an owner decision with the thermal analysis.

### Night solution (decision)

**Park on the dock overnight.** The dock bank carries the rover's survival load through the pad link. A rover that is stranded off the dock survives on its pack, and the budget says how long.

| Case | Rover pack needs (354 h) | Dock can deliver above its night reserve | Margin |
|---|---|---|---|
| Rescaled | ${f(dk(sN).needKWh, 0)} kWh | ${f(dk(sN).availKWh, 0)} kWh | ${f(dk(sN).margin, 2)}x |
| Rescaled + lower set points | ${f(dk(sT).needKWh, 0)} kWh | ${f(dk(sT).availKWh, 0)} kWh | ${f(dk(sT).margin, 2)}x |

* **Docked overnight: passes** (the margin above is the dock's ${f(POWER_DOCK.bankWh / 1000, 0)} kWh bank, ${POWER_DOCK.nightReserveSoc * 100} % night reserve, 85 % link). The first sizing, a 200 kWh bank, left only 1.09x; the bank was enlarged to 250 kWh.
* **Stranded off the dock: does NOT meet the old "≤ 25 % of the pack" limit.** The rescaled rover uses ${f(sN.packPct, 0)} % (${f(sT.packPct, 0)} % with the lower set points). Meeting 25 % needs about 100 W of isotope heat (RHU) and a 40 W survival hotel (${f(rhu.packPct, 0)} %). That is a hardware and policy decision, not a tuning change; \`tests/fdir.mjs\` E now states the docked and stranded cases separately (stranded limit ${60} %, with the reason).

## Hot day (regolith sink 230 K, sun 9° up on one side at cos 0.99, avionics + LiDAR + camera + comms ${ROVER.avionicsW + ROVER.lidarW + ROVER.cameraW + ROVER.commsW} W)

| Case | Vault °C, clean radiator (α ${RAD_ALPHA.clean}) | Vault °C, dusty (α ${RAD_ALPHA.dusty}) | Hot limit |
|---|---|---|---|
| Old 12 m² | ${f(hot(OLD, RAD_ALPHA.clean))} | ${f(hot(OLD, RAD_ALPHA.dusty))} | ${THERMAL.vault.hotC} °C |
| Rescaled ${f(THERMAL.vault.radArea, 2)} m² | ${f(hot(NEW, RAD_ALPHA.clean))} | ${f(hot(NEW, RAD_ALPHA.dusty))} | ${THERMAL.vault.hotC} °C |

| Case (charging at the 20 kW dock, 50 A) | Battery °C, clean | Battery °C, dusty | Hot limit |
|---|---|---|---|
| Old 3 m² / 0.4 W/K | ${f(hotDayBattery({ cfg: OLD }))} | ${f(hotDayBattery({ cfg: OLD, alpha: RAD_ALPHA.dusty }))} | ${THERMAL.battery.hotC} °C |
| Rescaled ${f(THERMAL.battery.radArea, 2)} m² | ${f(hotDayBattery({}))} | ${f(hotDayBattery({ alpha: RAD_ALPHA.dusty }))} | ${THERMAL.battery.hotC} °C |

A vault equilibrium above ${THERMAL.vault.hotC} °C means the thermal brain's shed-load mode (thermal.js: avionics low power, louvers open) is what holds the vault in a full-load day; this is reported, not hidden.
`;
if (process.argv.includes('--print')) console.log(out);
else { writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'THERMAL_BUDGET.md'), out); console.log(out); }
